    def _build_workflow_graph(self):
        """Build a LangGraph state graph that coordinates the workflow."""
        class WorkflowState(TypedDict, total=False):
            dataset_path: str
            target_column: str
            dataset_context: Optional[str]
            llm_context: Optional[str]
            test_size: float
            min_models: int
            max_models: int
            run_improvement: bool
            status: Literal["pending", "ok", "error", "success"]
            error: str
            memory_snapshot: Dict[str, Any]
        
        state_graph = StateGraph(WorkflowState)
        state_graph.add_node("preprocessing", self._graph_preprocessing)
        state_graph.add_node("llm_orchestration", self._graph_llm_orchestration)
        state_graph.add_node("improvement", self._graph_improvement)
        state_graph.add_node("persist_memory", self._graph_finalize_memory)
        
        state_graph.set_entry_point("preprocessing")
        state_graph.add_conditional_edges(
            "preprocessing",
            self._status_router,
            {"error": END, "ok": "llm_orchestration"}
        )
        state_graph.add_conditional_edges(
            "llm_orchestration",
            self._status_router,
            {"error": END, "ok": "improvement"}
        )
        state_graph.add_conditional_edges(
            "improvement",
            self._status_router,
            {"error": END, "ok": "persist_memory"}
        )
        state_graph.add_edge("persist_memory", END)
        
        return state_graph.compile()
    
    @staticmethod
    def _status_router(state: Dict[str, Any]) -> str:
        """Determine next edge based on state."""
        return "error" if state.get("status") == "error" else "ok"
    
    def _graph_preprocessing(self, state: Dict[str, Any]) -> Dict[str, Any]:
        """LangGraph node: run preprocessing agent."""
        csv_path = Path(state["dataset_path"])
        target_column = state["target_column"]
        dataset_context = state.get("dataset_context")
        try:
            self.run_preprocessing_agent(csv_path, target_column, context=dataset_context)
            return {"status": "ok", "error": ""}
        except Exception as exc:
            return {"status": "error", "error": str(exc)}
    
    def _graph_llm_orchestration(self, state: Dict[str, Any]) -> Dict[str, Any]:
        """LangGraph node: run LLM orchestrator."""
        try:
            self.run_llm_orchestrator(
                context=state.get("llm_context"),
                test_size=state.get("test_size", 0.2),
                min_models=state.get("min_models", 1),
                max_models=state.get("max_models", 3),
            )
            return {"status": "ok", "error": ""}
        except Exception as exc:
            return {"status": "error", "error": str(exc)}
    
    def _graph_improvement(self, state: Dict[str, Any]) -> Dict[str, Any]:
        """LangGraph node: run improvement agent. Skip when user selected full dataset (LLM Orchestrator already ran it)."""
        if not state.get("run_improvement", True):
            return {"status": "ok", "error": ""}
        # When user selected train on full dataset, LLM Orchestrator workflow already ran full training; skip improvement agent
        if self.memory.llm_orchestrator_memory.get("selected_model_for_full_training"):
            print("\nFull dataset training was selected; Improvement Agent skipped (full training already run by LLM Orchestrator).")
            self._add_workflow_entry("Improvement Agent", "Skipped (full dataset training was selected; run by LLM Orchestrator).")
            return {"status": "ok", "error": ""}
        try:
            self.run_improvement_agent()
            return {"status": "ok", "error": ""}
        except Exception as exc:
            return {"status": "error", "error": str(exc)}
    
    def _graph_finalize_memory(self, state: Dict[str, Any]) -> Dict[str, Any]:
        """Final LangGraph node: capture memory snapshot."""
        snapshot = self.get_memory()
        return {
            "memory_snapshot": snapshot,
            "status": "success"
        }


